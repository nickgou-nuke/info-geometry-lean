#!/usr/bin/env python3
"""Symbolically derive the six-bit PC word chart over GF(2).

This is a CAS derivation artifact.  It does not enumerate the 64 parameter
values.  Each generator is applied as I + e_i (p_i + I), with the Boolean
relations e_i^2=e_i reduced monomial-by-monomial.
"""
from pathlib import Path
import re
import subprocess
import sympy as sp

ROOT = Path(__file__).resolve().parents[1]
out = subprocess.run(["gap", "-q", str(ROOT / "scripts/export_carrier_pc_rows.g")],
                     cwd=ROOT, check=True, capture_output=True, text=True)
rows = {}
for line in out.stdout.splitlines():
    m = re.fullmatch(r"PCROW ([1-6]) ([0-9,;]*)", line.strip())
    if m:
        rows[int(m.group(1)) - 1] = [
            [int(x) for x in block.split(",") if x]
            for block in m.group(2).split(";")
        ]
assert set(rows) == set(range(6))

e = sp.symbols("e0:6")

def reduce_bool(poly, variables=None):
    variables = tuple(e) if variables is None else tuple(variables)
    p = sp.Poly(sp.expand(poly), *variables, modulus=2)
    terms = {}
    for mon, coeff in p.terms():
        capped = tuple(min(k, 1) for k in mon)
        terms[capped] = (terms.get(capped, 0) + int(coeff)) % 2
    result = 0
    for mon, coeff in terms.items():
        if coeff:
            term = 1
            for var, power in zip(variables, mon):
                if power:
                    term *= var
            result += term
    return sp.Poly(result, *variables, modulus=2).as_expr()

def add(*xs):
    return reduce_bool(sum(xs, sp.Integer(0)))

def mul(a, b):
    return reduce_bool(a * b)

def matrix(rows_):
    return [[sp.Integer(1 if j in row else 0) for j in range(8)]
            for row in rows_]

pc = [matrix(rows[i]) for i in range(6)]
I = [[sp.Integer(int(i == j)) for j in range(8)] for i in range(8)]

def matmul(a, b):
    return [[reduce_bool(sum(a[i][r] * b[r][j] for r in range(8)))
             for j in range(8)] for i in range(8)]

def factor(k):
    return [[add(I[i][j], mul(e[k], add(pc[k][i][j], I[i][j])))
            for j in range(8)] for i in range(8)]

def substitute(expr, values):
    return reduce_bool(expr.subs(values))

def depends_only(expr, vars_):
    poly = sp.Poly(expr, *e, modulus=2)
    return all(mon[i] == 0 for mon in poly.monoms()
               for i in range(6) if e[i] not in vars_)

def triangular_candidates(M, k):
    """Find f=e_k+q(e_0,...,e_{k-1}), without evaluating bit tuples."""
    found = []
    earlier = set(e[:k])
    later = set(e[k + 1:])
    for i in range(8):
        for j in range(8):
            expr = reduce_bool(M[i][j])
            zero_k = substitute(expr, {e[k]: 0})
            one_k = substitute(expr, {e[k]: 1})
            delta = reduce_bool(one_k + zero_k)
            if delta == 1 and depends_only(zero_k, earlier):
                found.append((i, j, str(zero_k)))
    return found

def singular_injectivity_certificate(M):
    """Ask Singular for ideal membership of e_i+f_i over GF(2)."""
    f = sp.symbols("f0:6")
    variables = tuple(e) + tuple(f)
    substitutions = dict(zip(e, f))
    equations = []
    for row in M:
        for entry in row:
            equations.append(reduce_bool(
                entry + entry.subs(substitutions), variables=variables))
    equations += [x**2 + x for x in variables]
    def singular_expr(expr):
        return str(expr).replace("**", "^")
    script = ["ring r=2,(%s),dp;" % ",".join(map(str, variables))]
    script.append("ideal I=%s;" % ",".join(singular_expr(x) for x in equations))
    script += ["option(redSB);", "ideal G=std(I);"]
    for x, y in zip(e, f):
        script.append('reduce(%s+%s,G);' % (x, y))
    script.append("reduce(1,G);")
    result = subprocess.run(["Singular", "-q"], input="\n".join(script),
                            text=True, capture_output=True, check=True)
    lines = [line.strip() for line in result.stdout.splitlines()
             if line.strip()]
    return lines

def anf_product(left, right):
    result = 0
    left_terms = [i for i in range(64) if (left >> i) & 1]
    right_terms = [i for i in range(64) if (right >> i) & 1]
    for x in left_terms:
        for y in right_terms:
            result ^= 1 << (x | y)
    return result

def generated_coordinate_algebra(entries):
    """Compute the symbolic GF(2)-algebra generated by matrix entries."""
    basis = {}
    queue = []
    def add_vector(vector):
        original = vector
        combo = 1 << len(queue)
        while vector:
            pivot = vector.bit_length() - 1
            if pivot in basis:
                vector ^= basis[pivot]
            else:
                basis[pivot] = vector
                queue.append(original)
                return True
        return False
    add_vector(1)
    for _, _, vector in entries:
        add_vector(vector)
    changed = True
    while changed and len(queue) < 64:
        changed = False
        old = list(queue)
        for left in old:
            for right in old:
                changed |= add_vector(anf_product(left, right))
                if len(queue) == 64:
                    break
            if len(queue) == 64:
                break
    return basis, queue

def generated_algebra_with_expressions(entries):
    """Return input-coordinate recovery expressions as output-entry polynomials."""
    basis = {}
    queue = []
    def xor_expr(a, b):
        return a.symmetric_difference(b)
    def mul_expr(a, b):
        return {x.union(y) for x in a for y in b}
    def add_vector(vector, expr):
        while vector:
            pivot = vector.bit_length() - 1
            if pivot in basis:
                old_vector, old_expr = basis[pivot]
                vector ^= old_vector
                expr = xor_expr(expr, old_expr)
            else:
                basis[pivot] = (vector, expr)
                queue.append((vector, expr))
                return True
        return False
    add_vector(1, {frozenset()})
    for index, (_, _, vector) in enumerate(entries):
        add_vector(vector, {frozenset({index})})
    changed = True
    while changed and len(queue) < 64:
        changed = False
        old = list(queue)
        for left_vector, left_expr in old:
            for right_vector, right_expr in old:
                changed |= add_vector(anf_product(left_vector, right_vector),
                                      mul_expr(left_expr, right_expr))
                if len(queue) == 64:
                    break
            if len(queue) == 64:
                break
    recovered = []
    for k in range(6):
        vector = 1 << (1 << k)
        expr = set()
        while vector:
            pivot = vector.bit_length() - 1
            if pivot not in basis:
                expr = None
                break
            old_vector, old_expr = basis[pivot]
            vector ^= old_vector
            expr = xor_expr(expr, old_expr)
        recovered.append(expr)
    return recovered

def bits_mul(left, right):
    result = 0
    for x in range(left.bit_length()):
        if (left >> x) & 1:
            for y in range(right.bit_length()):
                if (right >> y) & 1:
                    result ^= 1 << (x | y)
    return result

def bits_xor_sum(values):
    result = 0
    for value in values:
        result ^= value
    return result

def bits_eval_q(expr_bits, q, variables=6):
    """Evaluate a Boolean ANF in q[0],...,q[5]."""
    result = 0
    for monomial in range(1 << variables):
        if (expr_bits >> monomial) & 1:
            term = 1
            for k in range(variables):
                if (monomial >> k) & 1:
                    term = bits_mul(term, q[k])
            result ^= term
    return result

def lift_bits(bits, shift):
    result = 0
    for monomial in range(bits.bit_length()):
        if (bits >> monomial) & 1:
            result ^= 1 << (monomial << shift)
    return result

def eval_recovery_bits(expr, matrix_bits):
    result = 0
    for monomial in expr:
        term = 1
        for index in monomial:
            i, j, _ = entries[index]
            term = bits_mul(term, matrix_bits[i][j])
        result ^= term
    return result

for label, prepend in (("lean_product", False), ("reverse_matrix_product", True)):
    M = [row[:] for row in I]
    for k in range(6):
        M = matmul(factor(k), M) if prepend else matmul(M, factor(k))
    print("PC_WORD_MATRIX_ORDER=" + label)
    for k in range(6):
        print("TRIANGULAR", k, triangular_candidates(M, k))

    # Search the GF(2)-linear span of matrix entries for separators.  A
    # separator for e_k has the form e_k + q(e_0,...,e_{k-1}); this gives an
    # explicit triangular inverse and is a symbolic certificate, not a scan
    # over the 2^6 assignments.
    monomials = [tuple((n >> r) & 1 for r in range(6)) for n in range(64)]
    def coefficient_bits(expr):
        p = sp.Poly(reduce_bool(expr), *e, modulus=2)
        bits = 0
        for mon, coeff in p.terms():
            if int(coeff) & 1:
                n = sum(bit << r for r, bit in enumerate(mon))
                bits ^= 1 << n
        return bits

    entries = [(i, j, coefficient_bits(M[i][j]))
               for i in range(8) for j in range(8)]
    algebra_basis, algebra_queue = generated_coordinate_algebra(entries)
    recovered = []
    for k in range(6):
        target = 1 << (1 << k)
        vector = target
        while vector:
            pivot = vector.bit_length() - 1
            if pivot not in algebra_basis:
                break
            vector ^= algebra_basis[pivot]
        recovered.append(vector == 0)
    print("OUTPUT_COORDINATE_ALGEBRA_RECOVERS_INPUTS=", recovered)
    if label == "reverse_matrix_product":
        recovery_exprs = generated_algebra_with_expressions(entries)
        print("RECOVERY_EXPRESSION_SIZES=", [len(x) for x in recovery_exprs])
        for k, expr in enumerate(recovery_exprs):
            terms = []
            for monomial in sorted(expr, key=lambda m: (len(m), sorted(m))):
                factors = ["m%d%d" % entries[index][:2] for index in sorted(monomial)]
                terms.append("1" if not factors else "*".join(factors))
            print("RECOVER e%d = %s" % (k, " + ".join(terms)))
        matrix_bits = [[coefficient_bits(M[i][j]) for j in range(8)]
                       for i in range(8)]
        recovery_entries = sorted({(i, j) for expr in recovery_exprs
                                   for monomial in expr
                                   for i, j, _ in [entries[index]
                                                  for index in monomial]})
        for i, j in recovery_entries:
            print("RECOVERY_ENTRY m%d%d = %s" % (i, j, str(M[i][j])))
            print("FACTORED_ENTRY m%d%d = %s" %
                  (i, j, str(sp.factor(M[i][j]))))
        for k, expr in enumerate(recovery_exprs):
            assert eval_recovery_bits(expr, matrix_bits) == 1 << (1 << k)
        print("CAS_SYMBOLIC_PC_WORD_RECOVERY=PASS")

    ideal_check = singular_injectivity_certificate(M)
    assert ideal_check[:6] == ["0"] * 6
    assert ideal_check[6] != "0"
    print("SINGULAR_IDEAL_SEPARATION=", ideal_check[:6])
    print("SINGULAR_IDEAL_NONTRIVIAL=", ideal_check[6])
    if label == "reverse_matrix_product":
        print("CAS_SYMBOLIC_LEAN_PC_WORD_INJECTIVITY=PASS")
