#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Literal

Mode = Literal["lean-tactic", "code-patch", "coding"]
DEFAULT_ENDPOINT = "http://127.0.0.1:18889/v1"
DEFAULT_MODEL = "leanstral-gguf"
DEFAULT_STOP = ["<|im_end|>", "<|im_start|>"]
SCHEMA = "hermes_vibe_coding_agent.proposal.v1"


@dataclass(frozen=True)
class LeanstralConfig:
    endpoint: str = DEFAULT_ENDPOINT
    model: str = DEFAULT_MODEL
    timeout: int = 120
    max_tokens: int = 512
    temperature: float = 0.0
    stop: list[str] | None = None

    @property
    def stops(self) -> list[str]:
        return list(DEFAULT_STOP if self.stop is None else self.stop)

    @property
    def chat_completions_url(self) -> str:
        base = self.endpoint.rstrip("/")
        if base.endswith("/chat/completions"):
            return base
        return f"{base}/chat/completions"


Transport = Callable[[str, dict, int], dict]


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _strip_code_fence(text: str) -> str:
    stripped = text.strip()
    fence = re.fullmatch(r"```(?:[A-Za-z0-9_+.-]+)?\s*\n(.*?)\n?```", stripped, re.DOTALL)
    if fence:
        return fence.group(1).strip()
    starts = re.match(r"^```(?:[A-Za-z0-9_+.-]+)?\s*\n", stripped)
    if starts:
        stripped = stripped[starts.end() :]
        end = stripped.find("```")
        if end != -1:
            stripped = stripped[:end]
    return stripped.strip()


def sanitize_candidate(raw: str) -> str:
    """Turn a Vibe/Leanstral answer into a bounded proposal candidate.

    This intentionally does not prove anything. It just removes known local model
    continuations and Vibe presentation wrappers before Hermes/Lean validators see
    the proposal.
    """
    text = raw or ""
    for sentinel in DEFAULT_STOP:
        if sentinel in text:
            text = text.split(sentinel, 1)[0]
    lines: list[str] = []
    for line in text.splitlines():
        if line.startswith("Generated by Mistral Vibe"):
            break
        if line.startswith("Co-Authored-By: Mistral Vibe"):
            break
        lines.append(line)
    text = "\n".join(lines).strip()
    text = _strip_code_fence(text)
    return text.strip()


def build_messages(
    *,
    mode: Mode,
    task: str,
    context: str = "",
    imports: list[str] | None = None,
) -> list[dict[str, str]]:
    system = (
        "You are a bounded local Hermes/Vibe-style proposal generator. "
        "You run against a local Leanstral endpoint. Do not use tools. "
        "Do not claim verification, build success, audit success, or promotion authority. "
        "Your authority is proposal only. Return exactly the requested artifact, "
        "without markdown fences, prose prefaces, signatures, or follow-up questions."
    )
    imports = imports or []
    if mode == "lean-tactic":
        import_block = "\n".join(f"import {name}" for name in imports) or "import Mathlib"
        user = (
            "Generate one Lean 4 tactic candidate for this goal.\n\n"
            f"{import_block}\n\n"
            f"Lean 4 goal:\n{task.strip()}\n"
        )
        if context.strip():
            user += f"\nLocal context/hypotheses:\n{context.strip()}\n"
        user += "\nReturn only the tactic text."
    elif mode == "code-patch":
        user = (
            "Generate a minimal source-code patch proposal for the task below. "
            "Return only the patch text or exact replacement snippet; do not edit files.\n\n"
            f"Task:\n{task.strip()}\n"
        )
        if context.strip():
            user += f"\nContext:\n{context.strip()}\n"
    else:
        user = (
            "Generate a concise coding proposal for the task below. Do not claim it was run.\n\n"
            f"Task:\n{task.strip()}\n"
        )
        if context.strip():
            user += f"\nContext:\n{context.strip()}\n"
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def openai_chat_transport(url: str, payload: dict, timeout: int) -> dict:
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=body,
        method="POST",
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            data = response.read().decode("utf-8")
            return json.loads(data)
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"local Leanstral endpoint returned HTTP {exc.code}: {detail}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"local Leanstral endpoint unavailable: {exc.reason}") from exc


def extract_assistant_content(payload: dict) -> str:
    choices = payload.get("choices")
    if not isinstance(choices, list) or not choices:
        raise ValueError("OpenAI-compatible response has no choices")
    message = choices[0].get("message") if isinstance(choices[0], dict) else None
    if isinstance(message, dict):
        content = message.get("content")
        if isinstance(content, str):
            return content
    text = choices[0].get("text") if isinstance(choices[0], dict) else None
    if isinstance(text, str):
        return text
    raise ValueError("OpenAI-compatible response has no assistant content")


def propose(
    *,
    mode: Mode,
    task: str,
    context: str = "",
    imports: list[str] | None = None,
    config: LeanstralConfig | None = None,
    transport: Transport = openai_chat_transport,
) -> dict[str, object]:
    cfg = config or LeanstralConfig()
    messages = build_messages(mode=mode, task=task, context=context, imports=imports)
    prompt_material = json.dumps(messages, ensure_ascii=False, sort_keys=True)
    payload = {
        "model": cfg.model,
        "messages": messages,
        "temperature": cfg.temperature,
        "max_tokens": cfg.max_tokens,
        "stop": cfg.stops,
        "stream": False,
    }
    try:
        response = transport(cfg.chat_completions_url, payload, cfg.timeout)
        raw = extract_assistant_content(response)
        candidate = sanitize_candidate(raw)
        status = "ok" if candidate else "empty"
        error = None
    except Exception as exc:  # noqa: BLE001 - CLI wrapper returns JSON error packet
        response = None
        raw = ""
        candidate = ""
        status = "error"
        error = str(exc)
    result: dict[str, object] = {
        "schema": SCHEMA,
        "status": status,
        "mode": mode,
        "authority": "proposal",
        "promotion_allowed": False,
        "model": cfg.model,
        "endpoint": cfg.endpoint.rstrip("/"),
        "prompt_hash": sha256_text(prompt_material),
        "candidate": candidate,
        "raw_candidate": raw,
        "stop": cfg.stops,
        "max_tokens": cfg.max_tokens,
        "temperature": cfg.temperature,
    }
    if imports:
        result["imports"] = imports
    if error:
        result["error"] = error
    if response is not None:
        result["response_model"] = response.get("model")
    return result


def parse_imports(values: list[str]) -> list[str]:
    imports: list[str] = []
    for value in values:
        for item in value.split(","):
            item = item.strip()
            if item:
                imports.append(item)
    return imports


def _load_text_arg(value: str | None, path: str | None) -> str:
    if path:
        return Path(path).read_text(encoding="utf-8")
    return value or ""


def _fake_transport_from_file(path: Path) -> Transport:
    def fake_transport(url: str, payload: dict, timeout: int) -> dict:
        return json.loads(path.read_text(encoding="utf-8"))

    return fake_transport


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Bounded Hermes/Vibe-style local Leanstral proposal wrapper."
    )
    parser.add_argument("mode", choices=["lean-tactic", "code-patch", "coding"])
    parser.add_argument("--task", default=None, help="Task or Lean goal text.")
    parser.add_argument("--task-file", default=None, help="Read task text from a file.")
    parser.add_argument("--context", default="", help="Additional context.")
    parser.add_argument("--context-file", default=None, help="Read context from a file.")
    parser.add_argument("--import", dest="imports", action="append", default=[])
    parser.add_argument("--endpoint", default=os.environ.get("LEANSTRAL_ENDPOINT", DEFAULT_ENDPOINT))
    parser.add_argument("--model", default=os.environ.get("LEANSTRAL_MODEL", DEFAULT_MODEL))
    parser.add_argument("--timeout", type=int, default=int(os.environ.get("LEANSTRAL_TIMEOUT", "120")))
    parser.add_argument("--max-tokens", type=int, default=int(os.environ.get("LEANSTRAL_MAX_TOKENS", "512")))
    parser.add_argument("--temperature", type=float, default=float(os.environ.get("LEANSTRAL_TEMPERATURE", "0.0")))
    parser.add_argument("--fake-response", default=None, help="Testing hook: OpenAI-compatible JSON response file.")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(sys.argv[1:] if argv is None else argv)
    task = _load_text_arg(args.task, args.task_file).strip()
    if not task:
        print("--task or --task-file is required", file=sys.stderr)
        return 2
    context = _load_text_arg(args.context, args.context_file)
    cfg = LeanstralConfig(
        endpoint=args.endpoint,
        model=args.model,
        timeout=args.timeout,
        max_tokens=args.max_tokens,
        temperature=args.temperature,
    )
    transport = openai_chat_transport
    if args.fake_response:
        transport = _fake_transport_from_file(Path(args.fake_response))
    result = propose(
        mode=args.mode,
        task=task,
        context=context,
        imports=parse_imports(args.imports),
        config=cfg,
        transport=transport,
    )
    print(json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False))
    return 0 if result["status"] in {"ok", "empty"} else 1


if __name__ == "__main__":
    raise SystemExit(main())
