J = sp.Matrix([[0, 1], [-1, 0]])
Phi = S * J

assert S * S == I2
assert Phi * Phi == I2
assert J * J == -I2
assert S * Phi == J
assert Phi * S == -J
assert S * J == Phi
assert J * S == -Phi
assert J * Phi == S
