import os
import re
import shutil

ROOT_DIR = '/home/goutev/repos/info-geometry-lean/lean/InfoGeometry'
FORGA_DIR = os.path.join(ROOT_DIR, 'Forga')

def parse_imports(filepath):
    imports = []
    if not os.path.exists(filepath):
        return imports
    with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
        in_block_comment = False
        for line in f:
            line = line.strip()
            if not line:
                continue
            if line.startswith('/-'):
                in_block_comment = True
                if '-/' in line:
                    in_block_comment = False
                continue
            if in_block_comment:
                if '-/' in line:
                    in_block_comment = False
                continue
            if line.startswith('--'):
                continue
            match = re.match(r'^import\s+([A-Za-z0-9_\.]+)', line)
            if match:
                imports.append(match.group(1))
    return imports

def get_all_local_files():
    local_files = {}
    for root, dirs, files in os.walk(ROOT_DIR):
        # Do not recurse into Forga if it already exists
        if 'Forga' in dirs:
            dirs.remove('Forga')
        dirs[:] = [d for d in dirs if not d.startswith('.')]
        for file in files:
            if file.endswith('.lean'):
                fullpath = os.path.join(root, file)
                relpath = os.path.relpath(fullpath, ROOT_DIR)
                parts = os.path.normpath(relpath).replace('.lean', '').split(os.sep)
                mod_name = 'InfoGeometry.' + '.'.join(parts)
                local_files[mod_name] = relpath
    return local_files

def trace_imports(start_mod, local_files):
    visited = set()
    queue = [start_mod]
    while queue:
        current = queue.pop(0)
        if current in visited:
            continue
        visited.add(current)
        if current in local_files:
            filepath = os.path.join(ROOT_DIR, local_files[current])
            imports = parse_imports(filepath)
            for imp in imports:
                if imp.startswith('InfoGeometry.') and imp not in visited:
                    queue.append(imp)
    return visited

def main():
    local_files = get_all_local_files()
    imported_mods = trace_imports('InfoGeometry.All', local_files)
    
    unimported = {}
    for mod, relpath in local_files.items():
        if mod not in imported_mods:
            unimported[mod] = relpath

    print(f"Found {len(unimported)} unimported files.")

    # Create Forga directory
    if not os.path.exists(FORGA_DIR):
        os.makedirs(FORGA_DIR)

    # We also keep track of what needs to go in Forge.lean
    forge_imports = []

    # Copy files and rewrite imports
    for mod, relpath in sorted(unimported.items()):
        src_path = os.path.join(ROOT_DIR, relpath)
        dest_path = os.path.join(FORGA_DIR, relpath)
        dest_dir = os.path.dirname(dest_path)
        if not os.path.exists(dest_dir):
            os.makedirs(dest_dir)

        # Read content and rewrite imports
        with open(src_path, 'r', encoding='utf-8', errors='ignore') as f:
            lines = f.readlines()

        new_lines = []
        for line in lines:
            # We match 'import InfoGeometry.X'
            # Let's replace it if X is in unimported
            match = re.match(r'^(\s*import\s+)(InfoGeometry\.[A-Za-z0-9_\.]+)(.*)$', line)
            if match:
                prefix, imp_mod, suffix = match.groups()
                if imp_mod in unimported:
                    # Rename import to point to Forga
                    new_imp = imp_mod.replace('InfoGeometry.', 'InfoGeometry.Forga.')
                    line = f"{prefix}{new_imp}{suffix}\n"
            
            # Ensure line length is under 100 characters just in case
            if len(line) >= 100 and line.startswith('import InfoGeometry.Forga.'):
                pass
            new_lines.append(line)

        # Write to destination
        with open(dest_path, 'w', encoding='utf-8') as f:
            f.writelines(new_lines)

        # Module name under Forga
        forga_mod = mod.replace('InfoGeometry.', 'InfoGeometry.Forga.')
        forge_imports.append(forga_mod)

    # Generate Forge.lean
    forge_path = os.path.join(ROOT_DIR, 'Forge.lean')
    with open(forge_path, 'w', encoding='utf-8') as f:
        f.write("/-\n")
        f.write("Autogenerated Forge module importing all unimported modules.\n")
        f.write("-/\n\n")
        for imp in sorted(forge_imports):
            line = f"import {imp}\n"
            if len(line) >= 100:
                print(f"Warning: import line exceeds 100 characters: {line.strip()}")
            f.write(line)

    print(f"Generated {forge_path} with {len(forge_imports)} imports.")

    # Update All.lean to include import InfoGeometry.Forge
    all_path = os.path.join(ROOT_DIR, 'All.lean')
    with open(all_path, 'r', encoding='utf-8') as f:
        all_lines = f.readlines()

    # Check if InfoGeometry.Forge is already imported
    has_forge = any('InfoGeometry.Forge' in l for l in all_lines)
    if not has_forge:
        # Find a good place or append to end
        all_lines.append("\nimport InfoGeometry.Forge\n")
        with open(all_path, 'w', encoding='utf-8') as f:
            f.writelines(all_lines)
        print("Updated All.lean to import InfoGeometry.Forge.")
    else:
        print("All.lean already imports InfoGeometry.Forge.")

if __name__ == '__main__':
    main()
