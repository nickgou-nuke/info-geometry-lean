"""SymPy witness: non-invertible categorical symmetry on a Penrose/Cantor boundary.

Checks the transition from invertible wallpaper translations to non-invertible
aperiodic defects:

- a tripotent operator T satisfies T^3=T with spectrum {+1,-1,0};
- the zero eigenvalue gives a genuine kernel, hence non-invertibility;
- P=T^2 is an idempotent projector onto the surviving topological sectors;
- a noncommutative derivative d_Q(a)=[Q,a] is generated by an odd/glide Dirac
  operator Q with Q^2=H.
"""

import sympy as sp


def assert_matrix_zero(name, M):
    S = sp.simplify(M)
    if S != sp.zeros(*S.shape):
        raise AssertionError(f"{name} failed:\n{S}")

print("§1  Tripotent non-invertible defect")
T = sp.diag(1, -1, 0)
assert_matrix_zero("T^3=T", T**3 - T)
assert T.det() == 0
assert T.rank() == 2
assert T.nullspace() == [sp.Matrix([0, 0, 1])]
print("   T³=T, det(T)=0, kernel is one-dimensional ✓")

print("§2  Projector onto image sectors")
P = T**2
assert_matrix_zero("P^2=P", P**2 - P)
assert_matrix_zero("T P=T", T * P - T)
assert_matrix_zero("P T=T", P * T - T)
print("   P=T² is an idempotent support projector for the defect ✓")

print("§3  Spectrum {+1,-1,0}")
eigs = sorted(T.eigenvals().keys(), key=lambda x: float(x))
assert eigs == [-1, 0, 1]
# Minimal polynomial divides x(x-1)(x+1)=x^3-x.
assert_matrix_zero("minimal polynomial relation", T * (T - sp.eye(3)) * (T + sp.eye(3)))
print("   spectrum is exactly {-1,0,+1}; zero is the non-invertible sector ✓")

print("§4  Noncommutative derivative from glide supercharge")
Q = sp.Matrix([[0, 1], [1, 0]])
H = sp.eye(2)
assert_matrix_zero("Q^2=H", Q**2 - H)
a, b, c, d = sp.symbols("a b c d")
A = sp.Matrix([[a, b], [c, d]])
dA = Q * A - A * Q
# Leibniz rule for inner derivation: [Q,AB]=[Q,A]B + A[Q,B]
e, f, g, h = sp.symbols("e f g h")
B = sp.Matrix([[e, f], [g, h]])
left = Q * (A * B) - (A * B) * Q
right = (Q * A - A * Q) * B + A * (Q * B - B * Q)
assert_matrix_zero("commutator Leibniz", left - right)
print("   d_Q(a)=[Q,a] obeys Leibniz; Q²=H gives discrete SUSY derivative ✓")

print()
print("noninvertible_penrose_categorical_symmetry.py: All identities verified")
