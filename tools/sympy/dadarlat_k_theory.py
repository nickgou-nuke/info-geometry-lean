# 1. Bott periodicity: K0(C(S^2)) = Z ⊕ Z
# ---------------------------------------------------------------------------

def k0_sphere_2():
    """
    K0(C(S^2)) is free abelian on two generators:
      [e] = class of the trivial rank-1 projection (identity of C(S^2))
      [f] = class of the Bott projection in M2(C(S^2))
    """
    return {"generators": ["e", "f"], "rank": 2, "group": "Z ⊕ Z"}


def bott_projection():
    """
    The Bott projection f ∈ M2(C(S^2)).
    In the standard atlas, f is the rank-1 projection corresponding
    to the tautological line bundle on CP^1 ≅ S^2.

    K0(C(S^2)) = Z[e] ⊕ Z[f]  where [e] = 1, [f] has rank 1 and
    satisfies [f] = [e] - [f] in the reduced K0 (since S^2 is a
    suspension, the reduced K0 is Z generated by the Bott element).
    """
    e = Matrix([[1, 0], [0, 1]])  # trivial rank-2
    f = Matrix([[1, 0], [0, 0]])  # Bott projection (rank 1)
    return {"e": e, "f": f, "K0_generators": {"[e]": (1, 0), "[f]": (0, 1)}}


# ---------------------------------------------------------------------------
# 2. Building block Bn and its K-theory
# ---------------------------------------------------------------------------

def bn_k_theory(n: int):
    """
    Bn = (en + fn) M_{n+2}(C(S^2)) (en + fn)

    where en = e ⊕ ... ⊕ e  (n copies of trivial)
          fn = (e ⊕ ... ⊕ e) ⊕ f  (n-1 copies of e, then f)

    en + fn is a projection of rank n + 1 in M_{n+2}(C(S^2)).
    Bn is Morita equivalent to C(S^2), hence:

    K0(Bn) = Z^{2^n}  (free abelian of rank 2^n)
    K1(Bn) = 0

    Actually, the construction uses en = e (n copies?).
    From the paper: en = e (unit of C(S^2)), fn = (e ⊕ ... ⊕ e) ⊕ f
    with (n-1) copies of e. Bn = (en + fn) M_{n+2}(C(S^2)) (en + fn).

    K0(Bn) is freely generated by [en] and [fn], each Morita equivalent
    to a projection in C(S^2). So K0(Bn) ≅ Z^2.
    """
    rank = 2  # K0(Bn) ≅ Z^2 for each n
    generators = ["[en]", "[fn]"]
    return {"n": n, "K0_rank": rank, "K0_generators": generators, "K1": 0}


# ---------------------------------------------------------------------------
# 3. Infinite tensor product A = ⊗_{n=1}^∞ Bn
# ---------------------------------------------------------------------------

def tensor_product_k_theory(max_n: int = 5):
    """
    A = ⊗_{n=1}^∞ Bn where each Bn is Morita equivalent to C(S^2).

    By the Künneth formula for UCT C*-algebras:
    K0(A) = lim_{n→∞} K0(⊗_{k=1}^n Bk)

    Each Bk has K0(Bk) = Z^2 = Z[e_k] ⊕ Z[f_k].
    K0(⊗_{k=1}^n Bk) = K0(B1) ⊗ K0(B2) ⊗ ... ⊗ K0(Bn)
                     = (Z^2)^{⊗ n}
                     = Z^{2^n}

    The connecting map Z^{2^n} → Z^{2^{n+1}} sends x ↦ (x, x)
    (tensor with the identity element of the new factor).

    The direct limit of the system:
      Z^2 → Z^4 → Z^8 → ... → Z^{2^n} → ...   (maps: x ↦ (x, x))

    is isomorphic to C(K, Z), the group of continuous integer-valued
    functions on the Cantor set K.

    Proof: The limit of the dual system of finite sets {1,...,2^n}
    with surjective connecting maps (doubling) is the Cantor set K.
    Hence lim_{→} Z^{2^n} = C(K, Z) by Stone duality.
    """
    print(f"Computing K0(⊗ Bk) up to n={max_n}")

    # Explicit presentation of the connecting maps
    for n in range(1, max_n + 1):
        dim = 2 ** n
        dim_next = 2 ** (n + 1)
        print(f"  n={n}: Z^{dim} → Z^{dim_next}  via x ↦ (x, x)")

    print("\nLimit: K0(A) ≅ C(K, Z)  (continuous functions Cantor set → Z)")
    print("This is a divisible torsion-free abelian group of rank continuum.")
    return {"limit_group": "C(K, Z)", "is_torsion_free": True, "is_divisible": False}


# ---------------------------------------------------------------------------
# 4. Tensor with D and the Künneth formula
# ---------------------------------------------------------------------------

def kunneth_tensor(G0: str, H0: str, G1: str = "0", H1: str = "0"):
    """
    Künneth formula for UCT C*-algebras:
    K0(A ⊗ B) ≅ (K0(A) ⊗ K0(B)) ⊕ (K1(A) ⊗ K1(B))
    K1(A ⊗ B) ≅ (K0(A) ⊗ K1(B)) ⊕ (K1(A) ⊗ K0(B))

    For A = infinite tensor product (K1(A) = 0):
    K0(A ⊗ D) ≅ K0(A) ⊗ K0(D)

    If D is a Kirchberg algebra with torsion K-theory (e.g. On),
    then K0(A) ⊗ K0(D) = C(K, Z) ⊗ G where G is torsion.
    """
    print(f"Künneth: K0(A ⊗ D) ≅ {G0} ⊗ {H0}")

    # For torsion groups: C(K, Z) ⊗ G ≅ C(K, G)
    # because Z ⊗ G = G and tensor product commutes with direct limits
    result = f"C(K, {H0}) ⊕ C(K, Tor({G0}, {H1}))"
    print(f"  → {result}")
    return result


def compute_ep_k_theory(d_name: str, k0_d: str, k1_d: str = "0"):
    """
    Compute K-theory of the nontrivial O2-bundle EP (Example 1.2).

    F = A ⊗ D where:
    - A is the infinite tensor product (K0(A) = C(K, Z), K1(A) = 0)
    - D is a unital Kirchberg algebra with K*(D) = (G0, G1)
    - Both G0, G1 are countable abelian torsion groups

    By the Künneth formula:
    K0(F) = K0(A) ⊗ K0(D) ⊕ K1(A) ⊗ K1(D)
          = C(K, Z) ⊗ G0 ⊕ 0 ⊗ G1
          = C(K, G0)

    Since G0, G1 are torsion, all fibers of F are isomorphic to O2
    (by Kirchberg-Phillips classification).

    But K0(F) = C(K, G0) ≠ 0 if G0 ≠ 0, so F is not trivial
    (C(Z) ⊗ O2 has K0 = 0).
    """
    print(f"EP for D = {d_name}:")
    print(f"  K0(D) = {k0_d}, K1(D) = {k1_d}")
    print(f"  K0(EP) = C(K, {k0_d})")
    print(f"  Fibers: all ≅ O2 (torsion → KK-contractible → O2)")
    print(f"  Is EP trivial? {'No' if k0_d != '0' else 'Yes'}")

    return {"fiber": "O2", "K0_bundle": f"C(K, {k0_d})",
            "K0_trivial_bundle": "0", "is_nontrivial": k0_d != "0"}


