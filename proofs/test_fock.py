import sympy as sp
from sympy.physics.secondquant import (
    B, Bd, F, Fd, 
    Commutator,
    FockStateBosonKet, FockStateFermionKet, 
    apply_operators, wicks, evaluate_deltas
)

def test_fock():
    i, j, k, l = sp.symbols('i j k l')

    print("--- BOSONIC FOCK SPACE ---")
    create_b = Bd(i)
    annihilate_b = B(j)

    comm = Commutator(annihilate_b, create_b).doit()
    print(f"Bosonic Commutator [B(j), Bd(i)]: {comm}") 

    # Boson Ket takes occupation numbers (n_0, n_1, n_2)
    # Vacuum state with 3 modes initialized to 0
    vacuum_b = FockStateBosonKet((0, 0, 0))
    print(f"Bosonic Vacuum: {vacuum_b}")

    # Create a particle in mode 1
    state_1_particle = apply_operators(Bd(1) * vacuum_b)
    print(f"Applying Bd(1) to vacuum: {state_1_particle}")


    print("\n--- FERMIONIC FOCK SPACE ---")
    
    # Fermion Ket takes a list of occupied modes (m_1, m_2, ...)
    # Note: modes should be > 0 because of a known SymPy quirk where mode 0 evaluates to False internally.
    print("Fermionic Anti-commutation is enforced internally (Pauli Exclusion Principle).")

    # Try creating a state with two fermions in mode 1
    invalid_fermion_state = FockStateFermionKet((1, 1))
    print(f"Fermion State |1, 1> (two particles in same mode): {invalid_fermion_state}  <- Algebraically evaluates to Zero!")

    valid_fermion = FockStateFermionKet((1, 2))
    print(f"Valid Fermion State |1, 2> (particles in modes 1 and 2): {valid_fermion}")


    print("\n--- SYMBOLIC WICK'S THEOREM (FERMIONS) ---")
    f_i_dagger = Fd(i)
    f_j_dagger = Fd(j)
    f_k = F(k)
    f_l = F(l)

    # 4-Fermion operator string
    operator_string = f_k * f_l * f_i_dagger * f_j_dagger

    vev = wicks(operator_string, keep_only_fully_contracted=True)
    print("Raw Wick Contraction <0| F_k F_l Fd_i Fd_j |0>:")
    print(vev) 

    # We can symbolically evaluate dummy variables generated by wicks
    summed_expr = evaluate_deltas(vev.subs(l, j))
    print("\nAfter summing over index l (setting l -> j):")
    print(summed_expr)

if __name__ == "__main__":
    test_fock()
