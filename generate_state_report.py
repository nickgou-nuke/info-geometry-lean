#!/usr/bin/env python3
import subprocess, os, datetime

def run_cmd(cmd):
    result = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return result.stdout.strip()

def main():
    cwd = os.path.abspath(os.path.dirname(__file__))
    # Git info
    commit = run_cmd("git rev-parse HEAD")
    date = run_cmd("git log -1 --format=%cd --date=iso")
    # Lean version
    lean_ver = run_cmd("lean --version")
    # Quick build status (try building a representative module)
    build_output = run_cmd("lake build InfoGeometry.All")
    build_success = "error" not in build_output.lower()
    status = "✅ Build succeeded" if build_success else "❌ Build failed"
    # Count sorry occurrences
    sorry_count = run_cmd("grep -R \"sorry\" -n lean | wc -l")
    # Write report
    report_path = os.path.join(cwd, "CURRENT_STATE_REPORT.md")
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("# info-geometry-lean — Current State Report\n\n")
        f.write(f"> **Last Updated**: {date}\n")
        f.write(f"> **Lean Version**: {lean_ver}\n")
        f.write(f"> **Build Status**: {status}\n")
        f.write(f"> **Commit**: {commit}\n")
        f.write(f"> **Sorry Count**: {sorry_count}\n")
        f.write("\n---\n\n")
        f.write("*Generated by generate_state_report.py*\n")
    print("Report generated at", report_path)

if __name__ == "__main__":
    main()
