"""CAS discovery check for the native flag-stabilizer peel boundary.

This is evidence only.  It computes the subgroup generated by the four
native flag-stabilizer PC generators and checks the current six-step
``fullPeel`` on its elements.  No result from this script is a Lean theorem.
The exported matrices must still be translated and read back by Lean.
"""

import numpy as np

from verify_full_peel_residual_cas import I, mm, peel, s_gens, word


def subgroup(generators):
    """Close a finite matrix set under multiplication and inverses."""
    seen = {I.tobytes(): I}
    pending = [I]
    while pending:
        current = pending.pop()
        for generator in generators:
            candidate = mm(current, generator)
            key = candidate.tobytes()
            if key not in seen:
                seen[key] = candidate
                pending.append(candidate)
    return list(seen.values())


def main():
    # The repository order is pc1, pc2, pc3, pc4, pc5, pc6.
    flag_generators = [s_gens[0], s_gens[1], s_gens[2], s_gens[4]]
    elements = subgroup(flag_generators)
    print("FLAG_STABILIZER_GENERATED_CARD=", len(elements))

    failures = []
    for index, element in enumerate(elements):
        bits, residual = peel(element)
        if not (residual == I).all():
            failures.append((index, bits, residual))

    print("FULL_PEEL_IDENTITY_FAILURES=", len(failures))
    if failures:
        print("FIRST_FAILURE_BITS=", failures[0][1])
        raise SystemExit(1)
    print("FULL_PEEL_IDENTITY_ON_GENERATED_FLAG_STABILIZER=PASS")

    basis_vectors = {
        3: np.array([0, 0, 0, 1, 0, 0, 0, 0], dtype=np.int64),
        5: np.array([0, 0, 0, 0, 0, 1, 0, 0], dtype=np.int64),
        6: np.array([0, 0, 0, 0, 0, 0, 1, 0], dtype=np.int64),
    }
    for index, vector in basis_vectors.items():
        fixed = all(np.array_equal((peel(element)[1] @ vector) % 2, vector)
                    for element in elements)
        print(f"FULL_PEEL_BASIS8_{index}_FIXED=", "PASS" if fixed else "FAIL")
        if not fixed:
            raise SystemExit(1)


if __name__ == "__main__":
    main()
