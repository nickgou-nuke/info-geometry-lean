"""SymPy witness: Cl(1,1) CPT atom and signum limit.

The squashed modular boost tanh(v/2) eps tends to sgn(v) eps at the
boundary.  The discrete boundary atom is generated by eps^2=+1 and J^2=-1
with eps J = - J eps, giving Cl(1,1) ≅ M_2(R).
"""

import sympy as sp

print("§1  Cl(1,1) real matrix atom")
eps = sp.Matrix([[0, 1], [1, 0]])        # scale signum, square +1
J = sp.Matrix([[0, -1], [1, 0]])         # modular glide/CPT conjugation, square -1
I2 = sp.eye(2)
Z2 = sp.zeros(2)
assert eps**2 == I2
assert J**2 == -I2
assert eps*J + J*eps == Z2
CPT = eps*J
assert CPT**2 == I2
print("   eps²=1, J²=-1, {eps,J}=0, (eps J)²=1 ✓")

print("§2  Signum as boundary limit of squashing")
v = sp.symbols("v", real=True)
F = sp.tanh(v/2) * eps
assert sp.limit(sp.tanh(v/2), v, sp.oo) == 1
assert sp.limit(sp.tanh(v/2), v, -sp.oo) == -1
print("   tanh(v/2) eps -> ±eps at infinite rapidity ✓")

print("§3  Normalized boost signum")
# For concrete nonzero samples, K/|v| = sign(v) eps.
for val in [-3, -1, 1, 4]:
    K = val * eps
    signum = K / abs(val)
    expected = (1 if val > 0 else -1) * eps
    assert signum == expected
print("   K/|v| = sgn(v) eps for K=v eps ✓")

print()
print("cpt_atom_signum.py: All identities verified")
