def test_sanitize_candidate_removes_chatml_fences_and_vibe_footer() -> None:
    raw = """```lean
rfl
```
Generated by Mistral Vibe.
Co-Authored-By: Mistral Vibe <vibe@mistral.ai>
<|im_start|>user
ignore this stale continuation
"""

    assert agent.sanitize_candidate(raw) == "rfl"


