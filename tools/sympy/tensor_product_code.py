# Pauli matrices
I2 = eye(2)
X = Matrix([[0, 1], [1, 0]])
Y = Matrix([[0, -I], [I, 0]])
Z = Matrix([[1, 0], [0, -1]])

PAULI = {'I': I2, 'X': X, 'Y': Y, 'Z': Z}


# ===========================================================================
# 1. Stabilizer codes
# ===========================================================================

def pauli_group(n_qubits: int) -> list:
    """Generate the n-qubit Pauli group P_n (tensor products of {I,X,Y,Z})."""
    elements = []
    for paulis in itertools.product(['I', 'X', 'Y', 'Z'], repeat=n_qubits):
        mat = PAULI[paulis[0]]
        for p in paulis[1:]:
            mat = KroneckerProduct(mat, PAULI[p])
        elements.append((mat, ''.join(paulis)))
    return elements


def commutator(A: Matrix, B: Matrix) -> Matrix:
    """Commutator [A, B] = AB − BA."""
    return A * B - B * A


def stabilizer_group(generators: list) -> list:
    """Generate the full stabilizer group from a set of independent generators.

    The group is all products of subsets of generators: {∏_{i∈S} g_i | S ⊆ {1,...,k}}.
    Size = 2^k for k independent commuting generators.
    """
    k = len(generators)
    n = generators[0].rows
    group = [eye(n)]
    for g in generators:
        new = []
        for h in group:
            new.append(h * g)
        group.extend(new)
    return group


def stabilizer_code(generators: list) -> dict:
    """
    Define a stabilizer code from a set of commuting Pauli generators.

    The stabilizer group S is generated by the input list (must be independent
    and commuting). The code projector is Π = (1/|S|) Σ_{s∈S} s.
    """
    n_qubits = generators[0].rows.bit_length() - 1

    # Verify commutation
    for i, g1 in enumerate(generators):
        for j, g2 in enumerate(generators):
            if i != j:
                assert (g1 * g2 - g2 * g1).norm() < 1e-12, \
                    f"Generators {i},{j} don't commute"

    group = stabilizer_group(generators)
    S_size = len(group)

    # Projector: average of all group elements
    proj = zeros(2**n_qubits, 2**n_qubits)
    for g in group:
        proj += g
    proj = proj / S_size

    # Verify Π² = Π (projector)
    assert (proj * proj - proj).norm() < 1e-12, "Π² ≠ Π!"

    # Each independent generator halves the dimension
    # dim(code) = 2^n / 2^k = 2^{n-k}
    n_logical = n_qubits - len(generators)
    assert abs(trace(proj) - 2**n_logical) < 1e-12, \
        f"Tr(Π) = {trace(proj)} ≠ 2^{n_logical}"

    return {
        'projector': proj,
        'stabilizers': generators,
        'group': group,
        'n_qubits': n_qubits,
        'n_logical': n_logical,
    }


def logical_operators(code: dict) -> dict:
    """
    Find logical X and Z operators for each logical qubit.

    Logical operators commute with all stabilizers and anti-commute
    pairwise: {X̄_i, Z̄_i} = 0, [X̄_i, Z̄_j] = 0 for i ≠ j.
    """
    generators = code['stabilizers']
    n = code['n_qubits']
    paulis = pauli_group(n)

    # Find elements that commute with all stabilizers (normalizer)
    normalizer = []
    for mat, name in paulis:
        if all(commutator(mat, g).norm() < 1e-12 for g in generators):
            normalizer.append((mat, name))

    # From normalizer, pick representatives that are NOT in stabilizer group
    logicals = []
    stabilizer_names = set()  # would need to track which Paulis are stabilizers
    for mat, name in normalizer:
        # Check if mat is not proportional to identity on the code space
        projected = code['projector'] * mat * code['projector']
        if projected.norm() > 1e-12:
            logicals.append((mat, name))

    return {'normalizer': normalizer, 'logicals': logicals}


