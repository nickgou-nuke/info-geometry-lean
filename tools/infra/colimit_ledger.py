#!/usr/bin/env python3
"""Colimit ownership and comparison ledger.

Navigation and audit evidence only.  This tool extracts declaration headers
from repo-owned Lean sources, validates a curated owner/comparison registry
against those declarations, and cross-checks against the compiler-backed
declaration index when it covers the module.  It does not typecheck, prove,
or replace `lake` / Pantograph verification.

Normative rules implemented here:

* A `canonical_equiv` entry may only reference a named Lean declaration that
  actually exists in the source file it is registered against.
* Carriers that are supplied data (not a colimit) are labeled as such and are
  never promoted to universal colimits by the ledger.
* The ledger records provenance (source hashes, index metadata, olean
  freshness) so downstream consumers can tell inherited evidence from
  this-run evidence.

Usage:

    python3 tools/infra/colimit_ledger.py
    python3 tools/infra/colimit_ledger.py --json-out artifacts/colimit_ledger/ledger.json \
        --md-out artifacts/colimit_ledger/LEDGER.md

See `docs/COLIMIT_LEDGER_PROTOCOL.md` and `tools/data/colimit_registry.json`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

DEFAULT_REGISTRY = REPO / "tools" / "data" / "colimit_registry.json"
DEFAULT_JSON_OUT = REPO / "artifacts" / "colimit_ledger" / "ledger.json"
DEFAULT_MD_OUT = REPO / "artifacts" / "colimit_ledger" / "LEDGER.md"
DEFAULT_INDEX_DIR = REPO / "artifacts" / "dag" / "index"

SCAN_ROOT = REPO / "lean"
SCAN_EXCLUDES = (
    "/.kilo/",
    "/.lake/",
    "/__pycache__/",
    "/archive/",
    "/outdated/",
)

COLIMIT_TOKEN = re.compile(
    r"(?i)\b(colimit|cocone|directlimit|direct[_\s]?limit|inductivelimit|"
    r"inductive[_\s]?limit|inverse[_\s]?limit|inductive[_\s]?system|"
    r"direct[_\s]?system|dirlimit)\b"
)

HEADER_RE = re.compile(
    r"^(?P<indent>[ ]{0,4})"
    r"(?P<prefix>(?:@\[[^\]]*\]\s*)?"
    r"(?:(?:private|protected|noncomputable|unsafe|partial|scoped|local)\s+)*)"
    r"(?P<kind>theorem|lemma|def|abbrev|opaque|structure|class|inductive|instance)\b"
    r"(?P<rest>.*)$"
)

NAME_RE = re.compile(r"^[A-Za-z_\u00C0-\uFFFF«][\w'\u00C0-\uFFFF«».!?]*$")

NAMESPACE_RE = re.compile(r"^namespace\s+([\w.«»\u00C0-\uFFFF]+)\s*$")
SECTION_RE = re.compile(r"^section(?:\s+([\w.«»\u00C0-\uFFFF]+))?\s*$")
END_RE = re.compile(r"^end(?:\s+([\w.«»\u00C0-\uFFFF]+))?\s*$")
IMPORT_RE = re.compile(r"^import\s+([\w.«»\u00C0-\uFFFF.]+)\s*$")

TAG_RULES = (
    (
        "universal_property",
        re.compile(
            r"colimit\.desc|colimit\.hom_ext|IsColimit|descend|hom_ext|ι_desc|"
            r"\blift\b|\.desc\b|\bunique\b",
            re.I,
        ),
    ),
    (
        "stage_map",
        re.compile(
            r"colimit\.ι|inclusion|injection|ofStage|toLimit|\bstage\b|"
            r"stageMorphism|\bbond\b|transition|compat|naturality|\bstep\b",
            re.I,
        ),
    ),
    (
        "equivalence",
        re.compile(r"≅|\bIso\b|\bEquiv\b|≃|Equivalence|linearEquiv|equiv", re.I),
    ),
    (
        "completion",
        re.compile(r"Completion|Hilbert|Topological|UniformSpace|Complete", re.I),
    ),
    (
        "dual_inverse",
        re.compile(r"inverse|dual|projective|limitProjection", re.I),
    ),
    ("preservation", re.compile(r"Preserves|preserves", re.I)),
    (
        "kms_state",
        re.compile(r"kms|state|trace|modular|tracial", re.I),
    ),
    (
        "star_algebra",
        re.compile(r"⋆ₐ|StarAlg|StarRing|\bStar\b|involution", re.I),
    ),
)

GUARDRAIL = (
    "Generated by tools/infra/colimit_ledger.py. Source-derived declaration "
    "inventory and registry validation; not a proof check."
)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def module_of(rel: str) -> str:
    rel = rel[len("lean/") :] if rel.startswith("lean/") else rel
    if rel.endswith(".lean"):
        rel = rel[: -len(".lean")]
    parts = rel.split("/")
    if parts and parts[-1] == "default":
        parts = parts[:-1]
    return ".".join(parts)


def balance_delta(text: str) -> int:
    opens = text.count("(") + text.count("[") + text.count("{") + text.count("⟨")
    closes = text.count(")") + text.count("]") + text.count("}") + text.count("⟩")
    return opens - closes


def extract_name(rest: str) -> str:
    rest = rest.strip()
    if not rest:
        return ""
    token = rest.split(None, 1)[0]
    if NAME_RE.match(token) and token not in {"where", "deriving", "extends"}:
        return token
    return ""


def parse_file(path: Path, rel: str) -> dict:
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    module = module_of(rel)
    decls: list[dict] = []
    imports: list[str] = []
    ns_stack: list[tuple[str, str]] = []
    i = 0
    while i < len(lines):
        raw = lines[i]
        stripped = raw.strip()
        if stripped.startswith(("--", "/-", "/--")):
            i += 1
            continue
        imp = IMPORT_RE.match(stripped)
        if imp:
            imports.append(imp.group(1))
            i += 1
            continue
        ns = NAMESPACE_RE.match(stripped)
        if ns:
            ns_stack.append(("namespace", ns.group(1)))
            i += 1
            continue
        sec = SECTION_RE.match(stripped)
        if sec:
            ns_stack.append(("section", sec.group(1) or ""))
            i += 1
            continue
        end = END_RE.match(stripped)
        if end:
            name = end.group(1)
            if name:
                for idx in range(len(ns_stack) - 1, -1, -1):
                    if ns_stack[idx][1] == name or ns_stack[idx][1].endswith(
                        "." + name
                    ):
                        del ns_stack[idx:]
                        break
                else:
                    if ns_stack:
                        ns_stack.pop()
            elif ns_stack:
                ns_stack.pop()
            i += 1
            continue
        header = HEADER_RE.match(raw)
        if header:
            kind = header.group("kind")
            rest = header.group("rest")
            name = extract_name(rest)
            if not name:
                name = f"_anon_{kind}_{i + 1}"
            # Accumulate the declaration signature until the body starts.
            sig = stripped
            depth = balance_delta(stripped)
            j = i
            while (
                j + 1 < len(lines)
                and len(sig) < 2400
                and not (depth <= 0 and (":=" in sig or re.search(r"\bwhere\b", sig)))
            ):
                nxt_raw = lines[j + 1]
                nxt = nxt_raw.strip()
                if nxt.startswith(("--", "/-", "@[")) or not nxt:
                    break
                j += 1
                sig += " " + nxt
                depth += balance_delta(nxt)
                if depth <= 0 and (":=" in nxt or re.search(r"\bwhere\b", nxt)):
                    break
            sig = " ".join(sig.split())[:600]
            tags = [tag for tag, rx in TAG_RULES if rx.search(sig) or rx.search(name)]
            ns_prefix = ".".join(
                part for kind_, part in ns_stack if kind_ == "namespace" and part
            )
            full = f"{ns_prefix}.{name}" if ns_prefix else name
            decls.append(
                {
                    "name": name,
                    "full_name": full,
                    "kind": kind,
                    "line": i + 1,
                    "signature": sig,
                    "tags": tags,
                    "namespace": ns_prefix,
                }
            )
        i += 1
    return {"module": module, "decls": decls, "imports": imports}


def scan_sources() -> dict:
    files: dict[str, dict] = {}
    module_to_rel: dict[str, str] = {}
    for path in sorted(SCAN_ROOT.rglob("*.lean")):
        rel = path.relative_to(REPO).as_posix()
        if any(ex in rel for ex in SCAN_EXCLUDES):
            continue
        files[rel] = parse_file(path, rel)
        module = files[rel]["module"]
        module_to_rel.setdefault(module, rel)

    importers: dict[str, list[str]] = {}
    for rel, data in files.items():
        for mod in data["imports"]:
            importers.setdefault(mod, []).append(rel)
    return {"files": files, "module_to_rel": module_to_rel, "importers": importers}


def load_index_meta(index_dir: Path) -> dict | None:
    meta_path = index_dir / "meta.json"
    if not meta_path.exists():
        return None
    try:
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    meta["meta_path"] = meta_path.as_posix()
    return meta


def load_index_names(index_dir: Path) -> dict[str, dict] | None:
    decls_path = index_dir / "decls.jsonl"
    if not decls_path.exists():
        return None
    names: dict[str, dict] = {}
    with decls_path.open("r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            name = rec.get("name")
            if isinstance(name, str):
                names[name] = {
                    "kind": rec.get("kind"),
                    "module": rec.get("module"),
                    "file": rec.get("file"),
                    "line": rec.get("line"),
                }
    return names


def olean_status(module: str) -> str:
    olean = REPO / ".lake" / "build" / "lib" / "lean" / Path(*module.split(".")).with_suffix(".olean")
    rel = None
    for candidate, data in _SCAN_CACHE["files"].items():
        if data["module"] == module:
            rel = candidate
            break
    if not olean.exists():
        return "missing"
    if rel is None:
        return "present"
    src = REPO / rel
    try:
        return "fresh" if olean.stat().st_mtime >= src.stat().st_mtime else "stale"
    except OSError:
        return "present"


_SCAN_CACHE: dict = {"files": {}}


def registry_files(entries: list[dict]) -> list[str]:
    return sorted({e["file"] for e in entries})


def validate_entry(
    entry: dict,
    parsed_files: dict[str, dict],
    importers: dict[str, list[str]],
) -> dict:
    rel = entry["file"]
    errors: list[str] = []
    warnings: list[str] = []
    data = parsed_files.get(rel)
    if data is None:
        return {**entry, "errors": [f"file not found in scan: {rel}"], "decls_detail": []}
    by_name: dict[str, list[dict]] = {}
    for decl in data["decls"]:
        by_name.setdefault(decl["name"], []).append(decl)
    detail = []
    for name in entry.get("decls", []):
        hits = by_name.get(name)
        if not hits:
            errors.append(f"declaration not found in {rel}: {name}")
            continue
        hit = hits[0]
        detail.append(
            {
                "name": name,
                "kind": hit["kind"],
                "line": hit["line"],
                "tags": hit["tags"],
                "signature": hit["signature"],
            }
        )
    module = data["module"]
    direct_importers = sorted(set(importers.get(module, [])) - {rel})
    olean = olean_status(module)
    index_state = _SCAN_CACHE.get("index_names")
    in_index = module in _SCAN_CACHE.get("indexed_modules", set())
    entry_out = {
        "id": entry["id"],
        "title": entry.get("title", entry["id"]),
        "file": rel,
        "module": module,
        "role": entry.get("role"),
        "genuineness": entry.get("genuineness"),
        "category": entry.get("category"),
        "diagram": entry.get("diagram"),
        "notes": entry.get("notes", ""),
        "source_sha256": sha256_file(REPO / rel),
        "olean_status": olean,
        "decls_detail": detail,
        "declarations_expected": len(entry.get("decls", [])),
        "declarations_found": len(detail),
        "direct_importers": direct_importers[:40],
        "direct_importer_count": len(direct_importers),
        "compiler_index": {
            "module_covered": in_index,
            "module_decl_count": (
                sum(
                    1
                    for rec in (index_state or {}).values()
                    if rec.get("module") == module
                )
                if index_state and in_index
                else 0
            ),
        },
        "errors": errors,
        "warnings": warnings,
    }
    return entry_out


def candidate_summary(parsed_files: dict[str, dict], registered: set[str]) -> list[dict]:
    out = []
    for rel, data in parsed_files.items():
        if rel in registered:
            continue
        hits = [
            d
            for d in data["decls"]
            if COLIMIT_TOKEN.search(d["name"]) or COLIMIT_TOKEN.search(d["signature"])
        ]
        if not hits:
            continue
        out.append(
            {
                "file": rel,
                "module": data["module"],
                "matching_declarations": len(hits),
                "kinds": sorted({d["kind"] for d in hits}),
                "representative_decls": [
                    {
                        "name": d["name"],
                        "kind": d["kind"],
                        "line": d["line"],
                        "tags": d["tags"],
                    }
                    for d in hits[:10]
                ],
            }
        )
    out.sort(key=lambda item: (-item["matching_declarations"], item["file"]))
    return out


def probe_gaps(gaps: list[dict], parsed_files: dict[str, dict]) -> list[dict]:
    out = []
    for gap in gaps:
        matches: list[dict] = []
        for pattern in gap.get("probe", []):
            try:
                rx = re.compile(pattern)
            except re.error:
                continue
            for rel, data in parsed_files.items():
                for decl in data["decls"]:
                    if rx.search(decl["name"]) or rx.search(decl["signature"]):
                        matches.append(
                            {"file": rel, "name": decl["name"], "line": decl["line"]}
                        )
                        if len(matches) >= 25:
                            break
                if len(matches) >= 25:
                    break
        out.append(
            {
                **gap,
                "possible_existing": matches[:25],
                "possible_existing_count": len(matches),
                "probe_note": (
                    "name/signature regex matches across the scanned corpus; "
                    "navigation evidence only, requires owner-level review"
                ),
            }
        )
    return out


def write_markdown(ledger: dict, path: Path) -> None:
    lines: list[str] = []
    add = lines.append
    summary = ledger["summary"]
    add("# Colimit Ownership and Comparison Ledger")
    add("")
    add(f"> {GUARDRAIL}")
    add("")
    add(f"- Generated: `{ledger['generated_at']}`")
    add(f"- Generator: `{ledger['generator']}`")
    add(f"- Registry: `{ledger['registry_path']}`")
    add(f"- Scan scope: `{SCAN_ROOT.relative_to(REPO)}/**/*.lean`")
    add(f"- Source digest: `{summary['source_digest']}`")
    prov = ledger["provenance"]
    add(f"- Compiler decl index: `{prov['decl_index']['meta_path'] or 'absent'}`")
    idx = prov["decl_index"]
    add(
        "- Index metadata: "
        f"timestamp={idx.get('timestamp')} import_root={idx.get('import_root')} "
        f"source_hash={idx.get('source_hash')} node_count={idx.get('node_count')}"
    )
    add(
        "- Build verification this run: "
        f"{prov['lean_build_verification']}"
    )
    add("")
    add("## Summary")
    add("")
    add("| metric | value |")
    add("|---|---:|")
    add(f"| scanned Lean files | {summary['scanned_files']} |")
    add(f"| parsed declarations | {summary['parsed_declarations']} |")
    add(f"| registered owners | {summary['registered_entries']} |")
    add(f"| registered declarations found | {summary['registered_declarations_found']} |")
    add(f"| registry validation errors | {summary['registry_errors']} |")
    add(f"| comparison records | {summary['comparisons']} |")
    add(f"| gap records | {summary['gaps']} |")
    add(f"| unregistered candidate files | {summary['candidate_files']} |")
    add("")
    add("## Registered owners")
    add("")
    add(
        "| id | role | genuineness | category/diagram | file | decls | olean | importers |"
    )
    add("|---|---|---|---|---|---:|---|---:|")
    for entry in ledger["entries"]:
        ok = "OK" if not entry["errors"] else f"{len(entry['errors'])} error(s)"
        add(
            f"| `{entry['id']}` | {entry['role']} | {entry['genuineness']} | "
            f"{entry['category']} — {entry['diagram']} | `{entry['file']}` | "
            f"{entry['declarations_found']}/{entry['declarations_expected']} ({ok}) | "
            f"{entry['olean_status']} | {entry['direct_importer_count']} |"
        )
    add("")
    add("## Comparisons")
    add("")
    add("| id | kind | status | between | evidence |")
    add("|---|---|---|---|---|")
    for cmp_ in ledger["comparisons"]:
        ev = ", ".join(f"`{d}`" for d in cmp_.get("decls", [])) or "—"
        add(
            f"| `{cmp_['id']}` | {cmp_['kind']} | {cmp_['status']} | "
            f"{', '.join(cmp_.get('between', []))} | {ev} |"
        )
    add("")
    add("## Open obligations (candidate gaps)")
    add("")
    for gap in ledger["gaps"]:
        add(f"### `{gap['id']}` ({gap['status']})")
        add("")
        add(gap["description"])
        add("")
        if gap.get("suggested_next"):
            add(f"Suggested next step: {gap['suggested_next']}")
            add("")
        if gap.get("possible_existing"):
            add(
                "Probe matches (navigation evidence only): "
                + ", ".join(
                    f"`{m['file']}:{m['line']}` `{m['name']}`"
                    for m in gap["possible_existing"][:10]
                )
            )
            add("")
    if ledger.get("guardrails"):
        add("## Guardrails")
        add("")
        for g in ledger["guardrails"]:
            add(f"- {g}")
        add("")
    add("## Unregistered candidate files")
    add("")
    add(
        "Files with declarations whose name or signature mentions a colimit-family "
        "token and that are not part of a registered entry. These are review "
        "candidates, not claims."
    )
    add("")
    add("| file | matching decls | kinds | representatives |")
    add("|---|---:|---|---|")
    for cand in ledger["candidate_files"][:80]:
        reps = ", ".join(
            f"`{d['name']}`(:{d['line']})" for d in cand["representative_decls"][:4]
        )
        add(
            f"| `{cand['file']}` | {cand['matching_declarations']} | "
            f"{'/'.join(cand['kinds'])} | {reps} |"
        )
    add("")
    if summary["registry_errors"]:
        add("## Registry validation errors")
        add("")
        for entry in ledger["entries"]:
            for err in entry["errors"]:
                add(f"- `{entry['id']}`: {err}")
        add("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument("--json-out", type=Path, default=DEFAULT_JSON_OUT)
    parser.add_argument("--md-out", type=Path, default=DEFAULT_MD_OUT)
    parser.add_argument("--index-dir", type=Path, default=DEFAULT_INDEX_DIR)
    parser.add_argument(
        "--max-candidates",
        type=int,
        default=400,
        help="Maximum unregistered candidate files retained in the JSON.",
    )
    args = parser.parse_args()

    if not args.registry.exists():
        print(f"registry not found: {args.registry}", file=sys.stderr)
        return 2

    registry = json.loads(args.registry.read_text(encoding="utf-8"))
    scan = scan_sources()
    parsed_files: dict[str, dict] = scan["files"]
    _SCAN_CACHE["files"] = parsed_files

    index_meta = load_index_meta(args.index_dir)
    index_names = load_index_names(args.index_dir)
    _SCAN_CACHE["index_names"] = index_names or {}
    indexed_modules: set[str] = set()
    if index_names:
        indexed_modules = {
            rec["module"] for rec in index_names.values() if rec.get("module")
        }
    _SCAN_CACHE["indexed_modules"] = indexed_modules

    entries = [
        validate_entry(entry, parsed_files, scan["importers"])
        for entry in registry.get("entries", [])
    ]
    registered_files = {e["file"] for e in entries}

    comparisons = []
    for cmp_ in registry.get("comparisons", []):
        refs = []
        missing = []
        for ref in cmp_.get("decls", []):
            if "::" in ref:
                entry_id, name = ref.split("::", 1)
                entry = next((e for e in entries if e["id"] == entry_id), None)
                if entry is None:
                    missing.append(f"{ref} (unknown entry id)")
                    continue
                found = next(
                    (d for d in entry["decls_detail"] if d["name"] == name), None
                )
                if found is None:
                    missing.append(ref)
                else:
                    refs.append(
                        {
                            "entry": entry_id,
                            "name": name,
                            "file": entry["file"],
                            "line": found["line"],
                        }
                    )
            else:
                missing.append(f"{ref} (expected entry::decl form)")
        comparisons.append(
            {**cmp_, "resolved_decls": refs, "unresolved_decls": missing}
        )

    gaps = probe_gaps(registry.get("gaps", []), parsed_files)
    candidates = candidate_summary(parsed_files, registered_files)[: args.max_candidates]

    digest = hashlib.sha256()
    for rel in sorted(parsed_files):
        digest.update(rel.encode())
        digest.update(sha256_file(REPO / rel).encode())
    source_digest = digest.hexdigest()

    errors = sum(len(e["errors"]) for e in entries) + sum(
        len(c["unresolved_decls"]) for c in comparisons
    )
    ledger = {
        "schema": "info_geometry.colimit_ledger.v1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "tools/infra/colimit_ledger.py",
        "registry_path": args.registry.relative_to(REPO).as_posix()
        if args.registry.is_relative_to(REPO)
        else str(args.registry),
        "summary": {
            "scanned_files": len(parsed_files),
            "parsed_declarations": sum(len(d["decls"]) for d in parsed_files.values()),
            "registered_entries": len(entries),
            "registered_declarations_found": sum(
                e["declarations_found"] for e in entries
            ),
            "registry_errors": errors,
            "comparisons": len(comparisons),
            "gaps": len(gaps),
            "candidate_files": len(candidates)
            if len(candidates) < args.max_candidates
            else f">={args.max_candidates}",
            "source_digest": source_digest,
        },
        "provenance": {
            "scan_root": SCAN_ROOT.relative_to(REPO).as_posix(),
            "scan_excludes": list(SCAN_EXCLUDES),
            "decl_index": {
                "dir": args.index_dir.relative_to(REPO).as_posix()
                if args.index_dir.is_relative_to(REPO)
                else str(args.index_dir),
                "present": index_meta is not None,
                "meta_path": index_meta.get("meta_path") if index_meta else None,
                "timestamp": index_meta.get("timestamp") if index_meta else None,
                "import_root": index_meta.get("importRoot") if index_meta else None,
                "source_hash": index_meta.get("sourceHash") if index_meta else None,
                "node_count": index_meta.get("nodeCount") if index_meta else None,
                "caveat": (
                    "The existing compiler index was generated from a narrower "
                    "import root than the ledger scan; `compiler_index.module_covered` "
                    "records coverage per registered module."
                ),
            },
            "lean_build_verification": (
                "not performed by this generator; olean_status is inherited "
                "evidence from the shared build cache (mtime comparison only)"
            ),
        },
        "entries": entries,
        "comparisons": comparisons,
        "gaps": gaps,
        "guardrails": registry.get("guardrails", []),
        "candidate_files": candidates,
    }

    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    args.json_out.write_text(
        json.dumps(ledger, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    write_markdown(ledger, args.md_out)

    print(
        f"[colimit-ledger] entries={len(entries)} errors={errors} "
        f"comparisons={len(comparisons)} gaps={len(gaps)} "
        f"candidates={len(candidates)}"
    )
    print(f"[colimit-ledger] wrote {args.json_out.relative_to(REPO)}")
    print(f"[colimit-ledger] wrote {args.md_out.relative_to(REPO)}")
    return 0 if errors == 0 else 1


