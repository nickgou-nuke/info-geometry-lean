#!/usr/bin/env python3
"""Derive concrete PC commutator coordinates from the authoritative PC law.

The calculation is in the Boolean polynomial ring generated by two PC
coordinate vectors.  It uses the collector ``pcCombine`` and the inverse
formula, so it does not assume elementary F_2 root groups and does not
enumerate Boolean assignments.
"""

import sympy as sp


e = sp.symbols("e0:6")
f = sp.symbols("f0:6")
variables = e + f


def red(expr):
    poly = sp.Poly(sp.expand(expr), *variables, modulus=2)
    result = 0
    for monomial, coefficient in poly.terms():
        if int(coefficient) & 1:
            term = 1
            for variable, exponent in zip(variables, monomial):
                if exponent:
                    term *= variable
            result += term
    return sp.Poly(result, *variables, modulus=2).as_expr()


def combine(a, b):
    return [
        red(a[0] + b[0]),
        red(a[1] + b[1]),
        red(a[1] * b[0] + a[2] + b[2]),
        red(a[1] * b[0] + a[3] + a[4] * b[0] + b[3]),
        red(a[4] + b[4]),
        red(
            a[1] * a[2] * b[0]
            + a[1] * b[0] * b[1]
            + a[1] * b[0] * b[2]
            + a[1] * b[0]
            + a[1] * b[1]
            + a[2] * b[0]
            + a[2] * b[2]
            + a[3] * b[1]
            + a[4] * b[0] * b[1]
            + a[4] * b[1]
            + a[4] * b[2]
            + a[5]
            + b[5]
        ),
    ]


def inverse(a):
    return [
        a[0],
        a[1],
        red(a[0] * a[1] + a[2]),
        red(a[0] * a[1] + a[0] * a[4] + a[3]),
        a[4],
        red(
            a[0] * a[1] * a[2]
            + a[0] * a[1]
            + a[0] * a[2]
            + a[1] * a[3]
            + a[1] * a[4]
            + a[1]
            + a[2] * a[4]
            + a[2]
            + a[5]
        ),
    ]


zero = [0] * 6
assert all(red(x) == 0 for x in combine(e, inverse(e)))
assert all(red(x) == 0 for x in combine(inverse(e), e))

commutator = combine(combine(combine(e, f), inverse(e)), inverse(f))

print("PC_COMMUTATOR_SYMBOLIC=PASS")
print("PC_INVERSE_SYMBOLIC=PASS")
print("NO_ASSIGNMENT_ENUMERATION=PASS")
for index, coordinate in enumerate(commutator):
    print(
        f"COMM[{index}]="
        f"{sp.Poly(coordinate, *variables, modulus=2).as_expr()}"
    )


def basis(index):
    return [int(k == index) for k in range(6)]


print("GENERATOR_COMMUTATORS=")
for i in range(6):
    for j in range(i + 1, 6):
        value = combine(
            combine(combine(basis(i), basis(j)), inverse(basis(i))),
            inverse(basis(j)),
        )
        print(
            f"COMM_{i}_{j}="
            + ",".join(str(int(bool(red(coordinate)))) for coordinate in value)
        )
