#!/usr/bin/env python3
"""Regenerate a high-recall declaration index for symmetry/group review.

This is a navigation artifact, not a semantic classifier. It indexes named
Lean declaration headers whose names suggest group/symmetry structure or whose
types mention common group, action, root-system, or representation carriers.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "SYMMETRY_GROUP_CARRIER_DECLARATIONS.txt"

DECL_START = re.compile(
    r"^\s*(?:(?:private|protected|noncomputable|unsafe|opaque|theorem|lemma)\s+)*"
    r"(?:@[\w.]+\s+)*(def|abbrev|structure|class|inductive|theorem|lemma)\s+"
    r"([A-Za-z_][A-Za-z0-9_'.]*)"
)
NAME_CANDIDATE = re.compile(
    r"group|symmetr|action|automorph|\baut\b|\biso\b|weyl|"
    r"reflection|permutation|representation|stabilizer|normalizer|"
    r"equivariant|liealgebra|liegroup",
    re.IGNORECASE,
)
CARRIER_PATTERNS = {
    "group": re.compile(r"\b(?:Group|GroupWithZero|AddGroup|LieGroup)\b"),
    "subgroup": re.compile(r"\bSubgroup\b"),
    "hom": re.compile(r"\b(?:GroupHom|MonoidHom|MulEquiv|MulAut|MulAction|SMul)\b"),
    "root_lie": re.compile(
        r"\b(?:LieSubalgebra|LieAlgebra|WeylGroup|RootSystem|Representation)\b"
    ),
    "permutation": re.compile(r"\bEquiv\.Perm\b"),
    "operator": re.compile(r"\b(?:Module\.End|LinearMap\.GeneralLinearGroup|"
                            r"Matrix\.GeneralLinearGroup|CliffordAlgebra)\b"),
}
HEADER_END = re.compile(r"(?:\bwhere\b|:=|\bby\b)")


def result_type(header: str) -> str:
    """Return the declaration result after its top-level signature colon."""
    depth = 0
    for index, char in enumerate(header):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth = max(0, depth - 1)
        elif char == ":" and depth == 0:
            return re.split(r"\s*(?::=|\bwhere\b|\bby\b)", header[index + 1:], maxsplit=1)[0]
    return ""


def tracked_lean_files() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "-z", "--", "lean", "proofs"],
        cwd=ROOT,
        check=True,
        stdout=subprocess.PIPE,
    )
    return [ROOT / p for p in result.stdout.decode().split("\0")
            if p.endswith(".lean")]


def declarations(path: Path):
    lines = path.read_text(errors="replace").splitlines()
    i = 0
    while i < len(lines):
        match = DECL_START.match(lines[i])
        if not match:
            i += 1
            continue
        start = i
        header = [lines[i].strip()]
        i += 1
        while i < len(lines) and not HEADER_END.search(" ".join(header)):
            # A new declaration before a header terminator indicates an
            # unsupported syntax shape; retain the partial header honestly.
            if DECL_START.match(lines[i]):
                break
            header.append(lines[i].strip())
            i += 1
        text = " ".join(header)
        result = result_type(text)
        carriers = [key for key, pattern in CARRIER_PATTERNS.items()
                    if pattern.search(result)]
        name_hit = bool(NAME_CANDIDATE.search(match.group(2)))
        is_fact = match.group(1) in {"theorem", "lemma"}
        # Carrier mentions in hypotheses are extremely noisy. Index actual
        # result carriers, plus named law declarations whose result is often
        # an equality or action proposition rather than a group type.
        if name_hit or (carriers and not is_fact):
            yield start + 1, match.group(1), match.group(2), carriers, text


def main() -> None:
    files = tracked_lean_files()
    rows = []
    for path in files:
        rel = path.relative_to(ROOT).as_posix()
        for line, kind, name, carriers, header in declarations(path):
            rows.append((rel, line, kind, name, ",".join(carriers) or "name-only",
                         re.sub(r"\s+", " ", header).strip()))
    rows.sort(key=lambda row: (row[0], row[1], row[3]))
    OUTPUT.write_text(
        "# Generated by tools/repository_evolution/generate_symmetry_group_inventory.py\n"
        "# Scope: tracked repo-owned Lean under lean/ and proofs/; external submodules excluded.\n"
        "# These are declaration-header candidates, not a semantic census of distinct groups.\n"
        f"# Lean files scanned: {len(files)}\n"
        f"# Candidate declarations: {len(rows)}\n"
        "# Columns: path | line | declaration-kind | name | matched-carriers | header\n"
        + "\n".join(" | ".join(map(str, row)) for row in rows)
        + "\n"
    )
    print(f"scanned {len(files)} tracked Lean files; indexed {len(rows)} candidates")
    print(OUTPUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
