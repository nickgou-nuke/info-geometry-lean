import subprocess
import os

def generate_m2_dmodule_script(m2_script_path):
    m2_code = """
W_gr = QQ[x, y, X, Y]
I_char = ideal(x*X - y*Y, x*y - 1, X*Y)
dim_char = dim(W_gr / I_char)
print(dim_char)
exit(0)
"""
    os.makedirs(os.path.dirname(m2_script_path), exist_ok=True)
    with open(m2_script_path, "w") as f:
        f.write(m2_code.strip())
    print(f"[Tier 1] Wrote Macaulay2 script to {m2_script_path}")

def run_macaulay2(m2_script_path):
    print("[Tier 2] Executing Macaulay2 Characteristic Variety calculation...")
    result = subprocess.run(["M2", "--script", m2_script_path], capture_output=True, text=True)
    
    # Parse the output dimension securely from stdout
    output_lines = result.stdout.strip().split('\n')
    dim_val = int(output_lines[-1].strip())
    
    print(f"[Tier 2] Characteristic Variety Dimension = {dim_val}")
    assert dim_val == 2, f"D-Module is not holonomic! Expected 2, got {dim_val}"
    print("[Tier 2] Holonomicity Confirmed! The Singular Support is a Lagrangian Submanifold.")
    return dim_val

