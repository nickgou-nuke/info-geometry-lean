def classify_self_absorbing_k0():
    """
    Proposition 4.1 / Theorem 1.3: classify K0 groups of strongly
    self-absorbing Kirchberg algebras with the automatic triviality property.

    The possibilities for G = K0(D) are:
    1. G = 0     (K0(O2))
    2. G = Z     (K0(O∞))
    3. G = H ≤ Q such that 1/n ∈ H ⇒ 1/n² ∈ H  (K0(O∞ ⊗ U), U = UHF)

    Groups of type 3 are exactly the subgroups of Q that are
    "squares-closed": closed under the operation x ↦ x²/n when nx ∈ Z.
    Examples: Z[1/p], Z[1/pq], Q itself.

    The classification follows from three algebraic facts:
    (a) G is torsion-free (proved via Ext(G, G[p]) = 0 for all primes p)
    (b) Ze ⊂ G where e = [1D]
    (c) θ: G → G ⊗ G, θ(x) = x ⊗ e is an isomorphism
    (d) Conditions (a)-(c) force G ≅ Z or G ≤ Q with the square-closure property
    """
    print("Classification of K0 for strongly self-absorbing Kirchberg algebras:")
    print()

    cases = [
        ("O2", "0", "Cuntz algebra O2 — KK-contractible, K0 = 0"),
        ("O∞", "Z", "Cuntz algebra O∞ — K0 = Z, generator [1]"),
        ("O∞ ⊗ U", "H ≤ Q (square-closed)", "U = UHF of infinite type"),
    ]

    for name, k0, desc in cases:
        print(f"  {name:12s}  K0 = {k0:25s}  {desc}")

    # Verify square-closure property for Q-subgroups
    print("\nSquare-closure condition: if 1/n ∈ H then 1/n² ∈ H")
    print("  Z: trivially satisfied (no 1/n for n > 1)")
    print("  Z[1/p]: satisfied (1/p² = (1/p)·(1/p) ∈ Z[1/p])")
    print("  Q: satisfied (all fractions)")

    return cases


