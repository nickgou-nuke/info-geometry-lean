#!/usr/bin/env python3
"""Symbolic CAS certificate for the six-coordinate PC word map.

GAP supplies the carrier matrices.  Singular proves injectivity of the
ordered product symbolically: the ideal generated by
  M(e) - M(f), e_i^2-e_i, f_i^2-f_i
contains every e_i-f_i.  No Boolean assignment or word enumeration is used.
"""

from pathlib import Path
import re
import subprocess
import sympy as sp

ROOT = Path(__file__).resolve().parents[1]
gap = subprocess.run(
    ["gap", "-q", str(ROOT / "scripts/export_carrier_pc_rows.g")],
    cwd=ROOT, check=True, capture_output=True, text=True,
)
rows = {}
for line in gap.stdout.splitlines():
    m = re.fullmatch(r"PCROW ([1-6]) ([0-9,;]*)", line.strip())
    if m:
        rows[int(m.group(1)) - 1] = [
            [int(x) - 1 for x in block.split(",") if x]
            for block in m.group(2).split(";")
        ]
assert set(rows) == set(range(6))

e = sp.symbols("e0:6")
f = sp.symbols("f0:6")
all_vars = e + f

def reduce_bool(expr):
    poly = sp.Poly(sp.expand(expr), *all_vars, modulus=2)
    out = 0
    for mon, coeff in poly.terms():
        if int(coeff) & 1:
            term = 1
            for var, exponent in zip(all_vars, mon):
                if exponent:
                    term *= var
            out += term
    return sp.Poly(out, *all_vars, modulus=2).as_expr()

def matrix(i):
    return [[int(j in rows[i][r]) for j in range(8)] for r in range(8)]

def matmul(left, right):
    return [[reduce_bool(sum(left[i][k] * right[k][j] for k in range(8)))
             for j in range(8)] for i in range(8)]

I = [[int(i == j) for j in range(8)] for i in range(8)]

def factor(i, vars_):
    p = matrix(i)
    return [[reduce_bool(I[r][c] + vars_[i] * (p[r][c] + I[r][c]))
             for c in range(8)] for r in range(8)]

# In `SplitOctF2Aut`, multiplication is composition in the order
# `(g * h).1 X = h.1 (g.1 X)`.  Therefore the Lean word
# `p₀ * p₁ * ... * p₅` acts by the matrix product `M₅ ... M₁ M₀`.
# Keep this orientation explicit: using `M := M * factor(i)` would certify
# the GAP convention, not the Lean owner.
M = I
for i in range(6):
    M = matmul(factor(i, e), M)

equations = []
for row in M:
    for entry in row:
        equations.append(reduce_bool(entry + entry.xreplace(dict(zip(e, f)))))
equations += [x*x + x for x in all_vars]

def singular_name(x):
    return str(x).replace("**", "^")

ring = "ring r=2,(%s),dp;" % ",".join(map(str, all_vars))
script = [ring, "ideal I=%s;" % ",".join(singular_name(x) for x in equations),
          "option(redSB);", "ideal G=std(I);"]
script += ["reduce(%s+%s,G);" % (x, y) for x, y in zip(e, f)]
run = subprocess.run(["Singular", "-q"], input="\n".join(script),
                     text=True, capture_output=True, check=True)
answers = [line.strip() for line in run.stdout.splitlines() if line.strip()]
if len(answers) != 6 or any(line != "0" for line in answers):
    print("Singular reductions:", answers)
    raise SystemExit("Singular did not prove all six coordinate differences")
print("Singular Boolean ideal injectivity certificate: PASS")
print("PC word map is injective symbolically; no assignment enumeration used")
