#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable


KEYWORD_RE = re.compile(
    r"copyright|all rights reserved|licensed under|spdx-license-identifier|"
    r"community license|gnu lesser general public license|proprietary",
    re.IGNORECASE,
)


@dataclass
class PathAudit:
    path: str
    existed: bool
    file_count: int
    total_bytes: int
    hit_count: int
    sample_hits: list[str]


def run(cmd: list[str], cwd: Path | None = None) -> str:
    proc = subprocess.run(
        cmd,
        cwd=str(cwd) if cwd else None,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    return proc.stdout.strip()


def parse_excludes(path: Path) -> list[str]:
    rows: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        rows.append(line)
    return rows


def gather_stats(root: Path) -> tuple[int, int]:
    files = 0
    size = 0
    if root.is_file():
        return 1, root.stat().st_size
    for p in root.rglob("*"):
        if p.is_file():
            files += 1
            size += p.stat().st_size
    return files, size


def iter_text_lines(path: Path) -> Iterable[tuple[int, str]]:
    try:
        with path.open("rb") as f:
            head = f.read(4096)
            if b"\x00" in head:
                return
        with path.open("r", encoding="utf-8", errors="ignore") as f:
            for i, line in enumerate(f, start=1):
                yield i, line.rstrip("\n")
    except Exception:
        return


def sample_license_hits(root: Path, max_hits: int) -> list[str]:
    hits: list[str] = []
    if not root.exists():
        return hits
    files = [root] if root.is_file() else sorted(p for p in root.rglob("*") if p.is_file())
    for file in files:
        rel = file.relative_to(root.parent)
        for line_no, line in iter_text_lines(file):
            if KEYWORD_RE.search(line):
                snippet = line.strip()
                if len(snippet) > 160:
                    snippet = snippet[:157] + "..."
                hits.append(f"{rel}:{line_no}: {snippet}")
                if len(hits) >= max_hits:
                    return hits
    return hits


def write_stub(target_root: Path, rel_prefix: str, exclude_file: Path) -> None:
    stub_dir = target_root / rel_prefix.rstrip("/")
    stub_dir.mkdir(parents=True, exist_ok=True)
    stub_path = stub_dir / "README.EXCLUDED.md"
    stub_path.write_text(
        (
            "# Excluded Third-Party Path Stub\n\n"
            "This path was intentionally excluded from the public release export.\n\n"
            f"- Path prefix: `{rel_prefix}`\n"
            f"- Exclusion policy: `{exclude_file}`\n"
            "- Rationale: keep public-source release focused on project-owned code and documentation.\n"
        ),
        encoding="utf-8",
    )


def write_index(
    root: Path,
    *,
    prefix: str,
    commit: str,
    commit_time: str,
    ref: str,
    excludes: list[str],
    audits: list[PathAudit],
    exclude_file: Path,
) -> None:
    lines: list[str] = []
    lines.append("# Third-Party Release Index")
    lines.append("")
    lines.append("This file is generated by `tools/infra/export_public_release.py`.")
    lines.append("")
    lines.append("## Export metadata")
    lines.append(f"- Prefix: `{prefix}`")
    lines.append(f"- Git ref: `{ref}`")
    lines.append(f"- Commit: `{commit}`")
    lines.append(f"- Commit timestamp: `{commit_time}`")
    lines.append(f"- Exclusion policy file: `{exclude_file}`")
    lines.append("")
    lines.append("## Excluded path audit")
    for row in audits:
        status = "present+excluded" if row.existed else "missing"
        lines.append(f"- `{row.path}`")
        lines.append(f"  - status: {status}")
        lines.append(f"  - files before exclusion: {row.file_count}")
        lines.append(f"  - bytes before exclusion: {row.total_bytes}")
        lines.append(f"  - license-marker hits sampled: {row.hit_count}")
        for hit in row.sample_hits:
            lines.append(f"  - hit: `{hit}`")
    lines.append("")
    lines.append("## Notes")
    lines.append("- Public release export excludes third-party/reference zones and keeps stubs.")
    lines.append("- For internal forensic evidence including full build state, use:")
    lines.append("  - `tools/infra/create_evidence_bundle.sh --full-state`")
    lines.append("")
    (root / "THIRD_PARTY_RELEASE_INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def checksums(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    out["SHA256"] = run(["sha256sum", str(path)]).split()[0]
    out["SHA512"] = run(["sha512sum", str(path)]).split()[0]
    if shutil.which("b2sum"):
        out["BLAKE2B-512"] = run(["b2sum", str(path)]).split()[0]
    if shutil.which("openssl"):
        raw = run(["openssl", "dgst", "-sha3-512", str(path)])
        out["SHA3-512"] = raw.split("= ", 1)[-1].strip()
    return out


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export a clean public-release tree with third-party exclusions and stubs."
    )
    parser.add_argument("--ref", default="HEAD", help="Git ref to export (default: HEAD)")
    parser.add_argument("--prefix", default="info-geometry-lean-public", help="Root folder name inside export")
    parser.add_argument(
        "--out-dir",
        default="",
        help="Output directory (default: archive/public-release/<utc>_<shortsha>)",
    )
    parser.add_argument(
        "--exclude-list",
        default="tools/infra/archive_excludes.txt",
        help="Repo-relative exclusion policy file",
    )
    parser.add_argument("--max-hits", type=int, default=12, help="Sample hit lines per excluded path")
    parser.add_argument("--no-stubs", action="store_true", help="Do not create README stubs for excluded paths")
    parser.add_argument("--no-tarball", action="store_true", help="Do not generate .tgz bundle")
    args = parser.parse_args()

    root = Path(run(["git", "rev-parse", "--show-toplevel"]))
    commit = run(["git", "rev-parse", args.ref], cwd=root)
    short = run(["git", "rev-parse", "--short=12", args.ref], cwd=root)
    commit_time = run(["git", "show", "-s", "--format=%cI", args.ref], cwd=root)
    generated_utc = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")

    out_dir = Path(args.out_dir) if args.out_dir else root / "archive" / "public-release" / f"{generated_utc}_{short}"
    out_dir.mkdir(parents=True, exist_ok=True)
    exclude_file = (root / args.exclude_list).resolve()
    excludes = parse_excludes(exclude_file) if exclude_file.exists() else []

    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        # Export repository source at ref.
        with (tmp / "src.tar").open("wb") as f:
            subprocess.run(
                ["git", "archive", "--format=tar", f"--prefix={args.prefix}/", args.ref],
                cwd=root,
                check=True,
                stdout=f,
            )
        subprocess.run(["tar", "-xf", "src.tar"], cwd=tmp, check=True)

        tree_root = tmp / args.prefix
        audits: list[PathAudit] = []
        for rel in excludes:
            target = tree_root / rel
            existed = target.exists()
            file_count, total_bytes = gather_stats(target) if existed else (0, 0)
            hits = sample_license_hits(target, max_hits=args.max_hits) if existed else []
            if existed:
                if target.is_file():
                    target.unlink()
                else:
                    shutil.rmtree(target)
            if not args.no_stubs:
                write_stub(tree_root, rel, exclude_file)
            audits.append(
                PathAudit(
                    path=rel,
                    existed=existed,
                    file_count=file_count,
                    total_bytes=total_bytes,
                    hit_count=len(hits),
                    sample_hits=hits,
                )
            )

        write_index(
            tree_root,
            prefix=args.prefix,
            commit=commit,
            commit_time=commit_time,
            ref=args.ref,
            excludes=excludes,
            audits=audits,
            exclude_file=exclude_file,
        )

        manifest = {
            "generated_utc": generated_utc,
            "git_ref": args.ref,
            "git_commit": commit,
            "git_commit_short": short,
            "git_commit_time": commit_time,
            "prefix": args.prefix,
            "exclude_policy_file": str(exclude_file),
            "excluded_paths": excludes,
            "audits": [asdict(a) for a in audits],
        }
        (tree_root / "PUBLIC_RELEASE_MANIFEST.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )

        dst_tree = out_dir / args.prefix
        if dst_tree.exists():
            shutil.rmtree(dst_tree)
        shutil.copytree(tree_root, dst_tree, symlinks=True)

    if not args.no_tarball:
        tar_name = f"{args.prefix}-{short}-{generated_utc}.tgz"
        tar_path = out_dir / tar_name
        tar_proc = subprocess.Popen(
            [
                "tar",
                "--sort=name",
                "--mtime=UTC 1970-01-01",
                "--owner=0",
                "--group=0",
                "--numeric-owner",
                "-C",
                str(out_dir),
                "-cf",
                "-",
                args.prefix,
            ],
            stdout=subprocess.PIPE,
        )
        gzip_proc = subprocess.Popen(["gzip", "-n"], stdin=tar_proc.stdout, stdout=tar_path.open("wb"))
        assert tar_proc.stdout is not None
        tar_proc.stdout.close()
        tar_rc = tar_proc.wait()
        gz_rc = gzip_proc.wait()
        if tar_rc != 0 or gz_rc != 0:
            raise RuntimeError("failed to generate deterministic tar.gz export")

        sums = checksums(tar_path)
        cpath = out_dir / f"{args.prefix}-{short}-{generated_utc}.checksums.txt"
        with cpath.open("w", encoding="utf-8") as f:
            for k, v in sums.items():
                f.write(f"{k} {v}\n")

    print(f"Public release export ready: {out_dir}")
    print(f"Tree: {out_dir / args.prefix}")
    if not args.no_tarball:
        print("Includes .tgz and checksum manifest.")


if __name__ == "__main__":
    main()
