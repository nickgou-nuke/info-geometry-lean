#!/usr/bin/env python3
"""
Generate Macaulay2 script to compute the Tjurina number of the Unruh-Rindler superpotential
W = x^3 + x*theta*D.
Tjurina number = dim_QQ (QQ[x,theta,D] / <W, dW/dx, dW/dtheta, dW/dD>)
"""
import os

def main():
    output_dir = "scratch"
    os.makedirs(output_dir, exist_ok=True)
    m2_path = os.path.join(output_dir, "unruh_rindler_tjurina.m2")
    
    script = '''-- Generated by generate_unruh_rindler_tjurina.py
-- Define the polynomial ring in variables x, theta, D
R = QQ[x, theta, D];

-- Define the superpotential W = x^3 + x*theta*D
W = x^3 + x*theta*D;

-- Compute the partial derivatives
dW_dx = diff(x, W);  -- 3*x^2 + theta*D
dW_dtheta = diff(theta, W);  -- x*D
dW_dD = diff(D, W);  -- x*theta

-- Jacobian ideal (for Milnor) is <dW_dx, dW_dtheta, dW_dD>
-- Tjurina ideal is <W, dW_dx, dW_dtheta, dW_dD>
Tjurina_ideal = ideal(W, dW_dx, dW_dtheta, dW_dD);

-- Compute the dimension of the quotient ring R / Tjurina_ideal
D = dim(R / Tjurina_ideal);

-- Export the result
print(toString(D))
exit 0
'''
    
    with open(m2_path, 'w') as f:
        f.write(script)
    print(f"Generated Macaulay2 script at {m2_path}")

if __name__ == "__main__":
    main()