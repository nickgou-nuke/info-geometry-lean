import sympy as sp
import os

def kuntz_reduce_to_m2(expr_str):
    """
    Cleans up string variables into valid Macaulay2 syntax string formatting.
    """
    replacements = {
        "s1_star": "S1star",
        "s2_star": "S2star",
        "s1": "S1",
        "s2": "S2",
        "**": "^",
        "*": " * "
    }
    for old, new in replacements.items():
        expr_str = expr_str.replace(old, new)
    return expr_str

def generate_m2_pipeline_script(max_n):
    """
    Generates a full Macaulay2 script with dynamically expanded RFS operators.
    """
    s1, s2 = sp.Symbol('s1', commutative=False), sp.Symbol('s2', commutative=False)
    s1_star, s2_star = sp.Symbol('s1_star', commutative=False), sp.Symbol('s2_star', commutative=False)
    
    fermions = {1: s1 * s2_star}
    
    for i in range(2, max_n + 1):
        prev = fermions[i-1]
        fermions[i] = s1 * prev * s1_star - s2 * prev * s2_star
        
    script_lines = [
        "-- Automatically generated by Python RFS Pipeline Pipeline Generator",
        "loadPackage \"Dmodules\";",
        "",
        "-- 1. Ambient Free Algebra with Cuntz Relations",
        "A = QQ[S1, S2, S1star, S2star, Degrees => {1,1,1,1}, MonomialOrder => Lex];",
        "cuntzIdeal = ideal(S1star*S1 - 1, S2star*S2 - 1, S1star*S2, S2star*S1);",
        "O2 = A / cuntzIdeal;",
        "",
        "-- 2. Define Weyl / Bosonic sandbox for the representation target",
        f"W = QQ[x_1..x_{max_n}, D_1..D_{max_n}, WeylAlgebra => {{" + 
        ", ".join([f"x_{i} => D_{i}" for i in range(1, max_n + 1)]) + "}];",
        "",
        "-- 3. Dynamically Generated Recursive Fermion System Operators"
    ]
    
    for idx, expr in fermions.items():
        expanded_expr = str(sp.expand(expr))
        m2_expr = kuntz_reduce_to_m2(expanded_expr)
        script_lines.append(f"a_{idx} = substitute({m2_expr}, O2);")
        
    # Append the advanced state-predicate verification function
    script_lines.extend([
        "",
        "-- 4. Advanced State-Predicate Verification Function",
        "isAnnihilatedOnState = (operators, stateElement, sectorIdeal) -> (",
        "    allAnnihilated := true;",
        "    scan(operators, op -> (",
        "        fullAction := op * stateElement;",
        "        remainder := fullAction % sectorIdeal;",
        "        if remainder != 0 then (",
        "            allAnnihilated = false;",
        "        );",
        "    ));",
        "    return allAnnihilated;",
        ");",
        "",
        "-- 5. Verification Sandbox",
        "charge1Ideal = ideal(D_1 - 1, D_2 - 1, D_3 - 1);",
        "alpha_1 = 1 * D_1;",
        "excitedState = x_1^2;",
        "print(\"Is alpha_1 an annihilator for the excited state x_1^2?\");",
        "print(isAnnihilatedOnState({alpha_1}, excitedState, charge1Ideal));",
        "exit 0;"
    ])
        
    return "\n".join(script_lines)

if __name__ == "__main__":
    script_content = generate_m2_pipeline_script(max_n=3)
    output_path = "scratch/generated_pipeline.m2"
    with open(output_path, "w") as f:
        f.write(script_content)
    print(f"Generated M2 script written to {output_path}")
