# 2. Encoding isometry
# ===========================================================================

def encoding_isometry(code: dict) -> Matrix:
    """
    Construct the encoding isometry V : H_logical → H_physical.

    V maps |i⟩_L to the i-th basis vector of the code subspace.
    V satisfies V*V = I_logical (isometry condition).
    """
    proj = code['projector']
    k = code['n_logical']
    n = code['n_qubits']

    # Find an orthonormal basis for the code subspace (range of projector)
    # The columns of V are the basis vectors
    # For the projector Π, take eigenvectors with eigenvalue 1
    eig = proj.eigenvects()
    basis_vectors = []
    for val, mult, vecs in eig:
        if abs(val - 1) < 1e-12:
            for v in vecs:
                vn = v / v.norm()
                basis_vectors.append(vn)

    V = zeros(2**n, 2**k)
    for i, v in enumerate(basis_vectors[:2**k]):
        for j in range(2**n):
            V[j, i] = v[j]

    # Verify isometry: V*V = I_logical
    assert (conjugate(V.T) * V - eye(2**k)).norm() < 1e-12, \
        "Encoding isometry: V*V ≠ I"

    return V


# ===========================================================================
# 3. Knill-Laflamme error correction conditions
# ===========================================================================

def knill_laflamme_condition(code: dict, errors: list) -> bool:
    """
    Check the Knill-Laflamme error correction conditions.

    A code with projector P corrects errors {E_a} iff:
      P E_a* E_b P = C_ab P

    where C_ab is a Hermitian matrix of scalars.
    For non-degenerate codes: C_ab = δ_ab (diagonal).
    """
    P = code['projector']
    n_err = len(errors)
    C = zeros(n_err, n_err)

    for a in range(n_err):
        for b in range(n_err):
            Eab = conjugate(errors[a].T) * errors[b]
            lhs = P * Eab * P

            # Find C_ab such that P * E_a* E_b * P = C_ab * P
            # Check any nonzero entry of P (e.g. first diagonal element)
            p_ref = None
            for i in range(P.rows):
                if abs(P[i, i]) > 1e-12:
                    p_ref = P[i, i]
                    break
            if p_ref is None or abs(p_ref) < 1e-12:
                continue
            ratio = lhs[0, 0] / p_ref
            C[a, b] = ratio
            if (lhs - ratio * P).norm() > 1e-10:
                return False

    return (conjugate(C.T) - C).norm() < 1e-10


